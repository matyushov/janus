// janus.hpp — C++ wrapper over the libjanus C ABI (<janus/janus.h>). Header only, C++17.
//
// What it gives an application:
//
//   janus::Config cfg;                       // where the receiver is, certificates, share, quota
//   cfg.share.appliance_endpoint = "backup.example.org:7443";
//   ...
//   auto client = janus::Client::start(cfg, log_callback);   // runs INSIDE this process
//   janus::MountInfo m = client.mount_info();                // smb://127.0.0.1:<port>/<share> + user + password
//   ... mount `m` (janus/mount_macos.hpp, or your own code), use the files like any folder ...
//   client.stop(std::chrono::seconds(30));                   // wait for the upload, then close
//
// Error handling comes in two flavours, chosen at compile time:
//   * default: functions throw janus::Exception (derives from std::runtime_error);
//   * `#define JANUS_NO_EXCEPTIONS` before including (or compiling with -fno-exceptions): the
//     same functions return janus::Result<T> instead of T, and nothing throws.
// The `try_*` functions return Result<T> in BOTH flavours, so code can mix the two styles.
//
// Threading: every method may be called from any thread. Do not call stop() from the log
// callback (it is refused with Error::CallbackContext).
#pragma once

