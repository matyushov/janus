// ------------------------------------------------------------------ errors

/// What went wrong: a code (the JANUS_E_* constants) and the library's message.
struct Error {
  enum Code : int {
    InvalidArg = JANUS_E_INVALID_ARG,
    InvalidConfig = JANUS_E_INVALID_CONFIG,
    AlreadyStarted = JANUS_E_ALREADY_STARTED,
    Bind = JANUS_E_BIND,
    NotReady = JANUS_E_NOT_READY,
    Timeout = JANUS_E_TIMEOUT,
    Internal = JANUS_E_INTERNAL,
    CallbackContext = JANUS_E_CALLBACK_CONTEXT,
    Refused = JANUS_E_REFUSED,
    Journal = JANUS_E_JOURNAL,
  };
  int code = 0;
  std::string message;
};

#ifndef JANUS_NO_EXCEPTIONS
class Exception : public std::runtime_error {
 public:
  explicit Exception(Error e) : std::runtime_error(e.message), error_(std::move(e)) {}
  const Error& error() const noexcept { return error_; }
  int code() const noexcept { return error_.code; }

 private:
  Error error_;
};
#endif

/// A value or an Error. `if (r) use(*r);`
template <class T>
class Result {
 public:
  Result(T value) : value_(std::move(value)) {}
  Result(Error error) : error_(std::move(error)) {}
  explicit operator bool() const noexcept { return value_.has_value(); }
  bool ok() const noexcept { return value_.has_value(); }
  T& operator*() & { return *value_; }
  const T& operator*() const& { return *value_; }
  T* operator->() { return &*value_; }
  const T* operator->() const { return &*value_; }
  const Error& error() const noexcept { return error_; }
  /// The value, or throw (exceptions on) / abort (exceptions off).
  T take() {
#ifndef JANUS_NO_EXCEPTIONS
    if (!value_) throw Exception(error_);
#endif
    return std::move(*value_);
  }

 private:
  std::optional<T> value_;
  Error error_;
};

template <>
class Result<void> {
 public:
  Result() = default;
  Result(Error error) : ok_(false), error_(std::move(error)) {}
  explicit operator bool() const noexcept { return ok_; }
  bool ok() const noexcept { return ok_; }
  const Error& error() const noexcept { return error_; }
  void take() {
#ifndef JANUS_NO_EXCEPTIONS
    if (!ok_) throw Exception(error_);
#endif
  }

 private:
  bool ok_ = true;
  Error error_;
};

// The return type of the "plain" functions: T when exceptions are on, Result<T> when off.
#ifdef JANUS_NO_EXCEPTIONS
template <class T>
using Ret = Result<T>;
#define JANUS_RETURN(expr) return (expr)
#else
template <class T>
using Ret = T;
#define JANUS_RETURN(expr) return (expr).take()
#endif

